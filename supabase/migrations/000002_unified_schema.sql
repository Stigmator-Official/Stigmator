-- Auto-generate unique code
CREATE OR REPLACE FUNCTION generate_partnership_code()
RETURNS TRIGGER AS $$
DECLARE
    artist_initials TEXT;
    year TEXT;
    random_part TEXT;
BEGIN
    -- Get artist initials from profile
    SELECT COALESCE(SUBSTRING(UPPER(display_name), 1, 2), 'XX')
    INTO artist_initials
    FROM profiles
    WHERE id = NEW.artist_id;
    
    year := EXTRACT(YEAR FROM NOW())::TEXT;
    random_part := UPPER(SUBSTRING(MD5(NEW.id::TEXT), 1, 4));
    
    NEW.code := 'INK-' || artist_initials || year || '-' || random_part;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_partnership_code BEFORE INSERT ON partnership_codes
    FOR EACH ROW EXECUTE FUNCTION generate_partnership_code();

-- Calculate earnings for a sale with multiple partners
CREATE OR REPLACE FUNCTION calculate_garment_earnings(
    p_product_design_id UUID,
    p_sale_amount INTEGER
)
RETURNS TABLE (
    recipient_id UUID,
    recipient_type TEXT,
    amount INTEGER,
    percentage DECIMAL
) AS $$
DECLARE
    v_platform_fee INTEGER;
    v_remaining INTEGER;
    v_garment_design RECORD;
    v_partnership RECORD;
    v_design_share INTEGER;
BEGIN
    -- Platform takes 15%
    v_platform_fee := (p_sale_amount * 0.15)::INTEGER;
    v_remaining := p_sale_amount - v_platform_fee;
    
    -- Return platform fee
    RETURN QUERY SELECT 
        NULL::UUID,
        'platform'::TEXT,
        v_platform_fee,
        30.00::DECIMAL;
    
    -- Get all designs on this garment
    FOR v_garment_design IN 
        SELECT gd.*, d.artist_id
        FROM garment_designs gd
        JOIN designs d ON d.id = gd.design_id
        WHERE gd.product_design_id = p_product_design_id
    LOOP
        -- This design's share of the remaining 70%
        v_design_share := (v_remaining * (v_garment_design.revenue_percentage / 100))::INTEGER;
        
        -- Check if design has partnerships
        FOR v_partnership IN 
            SELECT dp.*, dp.artist_id as artist_user_id
            FROM garment_design_partnerships gdp
            JOIN design_partnerships dp ON dp.id = gdp.design_partnership_id
            WHERE gdp.product_design_id = p_product_design_id
            AND dp.design_id = v_garment_design.design_id
        LOOP
            -- Artist gets their share
            RETURN QUERY SELECT 
                v_partnership.artist_user_id,
                'artist'::TEXT,
                (v_design_share * (v_partnership.artist_share / 100))::INTEGER,
                (v_garment_design.revenue_percentage * (v_partnership.artist_share / 100))::DECIMAL;
            
            -- Client gets their share
            IF v_partnership.client_share > 0 THEN
                RETURN QUERY SELECT 
                    v_partnership.partner_id,
                    'client'::TEXT,
                    (v_design_share * (v_partnership.client_share / 100))::INTEGER,
                    (v_garment_design.revenue_percentage * (v_partnership.client_share / 100))::DECIMAL;
            END IF;
            
            -- Studio gets their share
            IF v_partnership.studio_share > 0 AND v_partnership.studio_id IS NOT NULL THEN
                RETURN QUERY SELECT 
                    v_partnership.studio_id,
                    'studio'::TEXT,
                    (v_design_share * (v_partnership.studio_share / 100))::INTEGER,
                    (v_garment_design.revenue_percentage * (v_partnership.studio_share / 100))::DECIMAL;
            END IF;
        END LOOP;
        
        -- If no partnerships, artist gets 100% of design share
        IF NOT EXISTS (
            SELECT 1 FROM garment_design_partnerships 
            WHERE product_design_id = p_product_design_id
            AND design_partnership_id IN (
                SELECT id FROM design_partnerships WHERE design_id = v_garment_design.design_id
            )
        ) THEN
            RETURN QUERY SELECT 
                v_garment_design.artist_id,
                'artist'::TEXT,
                v_design_share,
                v_garment_design.revenue_percentage::DECIMAL;
        END IF;
    END LOOP;
    
    RETURN;
END;
$$ LANGUAGE plpgsql;

