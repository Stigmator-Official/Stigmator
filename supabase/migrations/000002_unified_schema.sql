-- Partnership Codes (Generated by artist for tattoo clients)
-- This is SEPARATE from garment uploads - it's the pre-arrangement
CREATE TABLE partnership_codes (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    code TEXT UNIQUE NOT NULL, -- e.g., "INK-ALEX-2024-X7K9"
    design_id UUID REFERENCES designs(id) ON DELETE CASCADE NOT NULL,
    artist_id UUID REFERENCES profiles(id) NOT NULL,
    studio_id UUID REFERENCES studios(id), -- Optional: linked studio
    
    -- Split configuration (percentages as integers, total must = 100)
    -- These splits are from the ARTIST'S SHARE only
    -- Platform takes 15% at garment level, these splits happen from remaining 85%
    artist_share INTEGER NOT NULL DEFAULT 50, -- Artist keeps this % of their earnings
    client_share INTEGER NOT NULL DEFAULT 20, -- Client (tattoo wearer) gets this %
    studio_share INTEGER NOT NULL DEFAULT 0,  -- Studio gets this % (optional)
    
    -- Validation: artist_share + client_share + studio_share = 100
    
    -- Status
    status TEXT NOT NULL CHECK (status IN ('active', 'redeemed', 'expired', 'revoked')) DEFAULT 'active',
    max_uses INTEGER DEFAULT 1, -- Usually 1:1 partnership, but can be multiple for flash
    uses_remaining INTEGER DEFAULT 1,
    
    -- Client info (filled when code is created, confirmed when redeemed)
    intended_client_name TEXT,
    intended_client_email TEXT,
    tattoo_location TEXT, -- e.g., "LEFT FOREARM", "FULL BACK"
    session_date DATE,
    notes TEXT,
    
    -- Timestamps
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    redeemed_at TIMESTAMPTZ,
    redeemed_by UUID REFERENCES profiles(id),
    
    -- Validation constraint
    CONSTRAINT valid_partnership_splits CHECK (artist_share + client_share + studio_share = 100),
    CONSTRAINT positive_partnership_splits CHECK (artist_share >= 0 AND client_share >= 0 AND studio_share >= 0)
);

-- User Design Partnerships (When someone redeems a code)
CREATE TABLE design_partnerships (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    partnership_code_id UUID REFERENCES partnership_codes(id) NOT NULL,
    design_id UUID REFERENCES designs(id) NOT NULL,
    artist_id UUID REFERENCES profiles(id) NOT NULL,
    partner_id UUID REFERENCES profiles(id) NOT NULL, -- The tattoo wearer (client)
    studio_id UUID REFERENCES studios(id), -- If studio is involved
    
    -- Their agreed split (copied from code at redemption)
    artist_share INTEGER NOT NULL,
    client_share INTEGER NOT NULL,
    studio_share INTEGER NOT NULL,
    
    -- Verification
    verification_status TEXT NOT NULL CHECK (verification_status IN ('pending', 'verified', 'rejected')) DEFAULT 'pending',
    verification_photo_url TEXT, -- Photo of the actual tattoo
    verified_at TIMESTAMPTZ,
    verified_by UUID REFERENCES profiles(id),
    
    -- Earnings tracking (from this specific partnership)
    total_earnings INTEGER DEFAULT 0, -- In cents
    lifetime_sales INTEGER DEFAULT 0,
    
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(design_id, partner_id) -- One partnership per design per person
);

